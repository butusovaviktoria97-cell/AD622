# Задание 2. Сравнение объемов продаж разных категорий товаров
# Условие:
# Маркетплейс подвел итоги продаж за месяц по четырем категориям товаров:
# •	Электроника — 450 тыс. руб.
# •	Одежда — 320 тыс. руб.
# •	Книги — 180 тыс. руб.
# •	Дом и сад — 290 тыс. руб.
# Постройте вертикальную столбчатовую диаграмму. Задайте для каждого
# столбика свой цвет, настройте ширину столбцов
# и добавьте сетку только по оси Y, чтобы было удобнее считывать значения.

product = ['Электроника','Одежда', 'Книги', 'Дом и сад']
sales= [450, 320, 180, 290]

colors = ['#3498db', '#2ecc71', '#e67e22', '#9b59b6']

plt.figure(figsize=(8, 7))

plt.bar(product,
        sales,
        color=colors,
        width=0.6,
        edgecolor='black',
        linewidth=0.5
        )

plt.title('Объем продаж разных категорий товаров за месяц', fontsize=14, fontweight='bold')
plt.xlabel('Категории товаров', fontsize=12)
plt.ylabel('Продажи (тыс. руб.)', fontsize=12)
plt.grid(axis='y', linestyle='--', color='grey', alpha=0.5)

plt.ylim(0, 500)

plt.show()
