
# создать срезы из списка [1, 2, 3, 4, 5, 6, 7]
n = list(range(1,8))
print(n) # [1, 2, 3, 4, 5, 6, 7]
print(n[-1::-1]) # [7, 6, 5, 4, 3, 2, 1]
print(n[6::-1]) #  [7, 6, 5, 4, 3, 2, 1]
print(n[::2]) #  [1, 3, 5, 7]
print(n[1::2]) #  [2, 4, 6]
print(n[:1:]) #  [1]
print(n[-1::]) # [7]
print(n[3:4:]) # [4]
print(n[4::]) # [5, 6, 7]
print(n[4:1:-1]) # [5, 4, 3]
print(n[2:5:]) # [3, 4, 5]
